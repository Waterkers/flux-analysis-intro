function m = messages(lang)
% All text the helpers print or put on plots, in English and German.
% To fix a translation, change it here; nothing else needs to change.
  en = struct( ...
    'loaded',        'Model loaded: E. coli core model with %d reactions, %d metabolites and %d genes.\n', ...
    'growth',        'Growth rate: %.3f per hour (the cells double every %.0f minutes).\n', ...
    'noGrowth',      'Growth rate: 0 - the cells cannot grow under these conditions.\n', ...
    'infeasible',    'No solution: the model cannot run under these conditions.\n', ...
    'medium',        'Food: glucose uptake up to %g, oxygen uptake up to %g (mmol per gram per hour).\n', ...
    'takesUp',       'The cells TAKE UP:', ...
    'releases',      'The cells RELEASE:', ...
    'none',          '  (nothing)', ...
    'fluxTitle',     'The %d busiest reactions', ...
    'fluxLabel',     'Flux (mmol per gram per hour)', ...
    'unknownGene',   'Unknown gene: %s', ...
    'knockedOut',    'Gene knocked out: %s (%s)\n', ...
    'essentialHead', '%d of %d genes are essential (without them the cells cannot grow):\n', ...
    'geneLine',      '  %-6s %-6s  growth without it: %.3f per hour\n', ...
    'xGlucose',      'Glucose uptake (mmol per gram per hour)', ...
    'yGrowth',       'Growth rate (per hour)', ...
    'unknownLang',   'Unknown language "%s": use ''en'' or ''de''.', ...
    'langSet',       'Language: English\n');
  de = struct( ...
    'loaded',        'Modell geladen: E.-coli-Kernmodell mit %d Reaktionen, %d Metaboliten und %d Genen.\n', ...
    'growth',        'Wachstumsrate: %.3f pro Stunde (die Zellen verdoppeln sich alle %.0f Minuten).\n', ...
    'noGrowth',      'Wachstumsrate: 0 - unter diesen Bedingungen können die Zellen nicht wachsen.\n', ...
    'infeasible',    'Keine Lösung: unter diesen Bedingungen kann das Modell nicht laufen.\n', ...
    'medium',        'Nahrung: Glukose-Aufnahme bis %g, Sauerstoff-Aufnahme bis %g (mmol pro Gramm pro Stunde).\n', ...
    'takesUp',       'Die Zellen NEHMEN AUF:', ...
    'releases',      'Die Zellen GEBEN AB:', ...
    'none',          '  (nichts)', ...
    'fluxTitle',     'Die %d aktivsten Reaktionen', ...
    'fluxLabel',     'Fluss (mmol pro Gramm pro Stunde)', ...
    'unknownGene',   'Unbekanntes Gen: %s', ...
    'knockedOut',    'Gen ausgeschaltet: %s (%s)\n', ...
    'essentialHead', '%d von %d Genen sind essenziell (ohne sie können die Zellen nicht wachsen):\n', ...
    'geneLine',      '  %-6s %-6s  Wachstum ohne dieses Gen: %.3f pro Stunde\n', ...
    'xGlucose',      'Glukose-Aufnahme (mmol pro Gramm pro Stunde)', ...
    'yGrowth',       'Wachstumsrate (pro Stunde)', ...
    'unknownLang',   'Unbekannte Sprache "%s": nimm ''en'' oder ''de''.', ...
    'langSet',       'Sprache: Deutsch\n');
  if strcmp(lang, 'de')
    m = de;
  else
    m = en;
  end
end
